import numpy as np
from scipy.linalg import lu

# Пример матрицы из лекции (3x3 с параметрами, здесь конкретные числа)
A = np.array([[2, 1, 0],
              [8, 7, 1],
              [0, 4, 9]]) # измененный пример для наглядности

# Получение P, L, U разложения
# Scipy возвращает P (матрицу перестановок), L и U
P, L, U = lu(A)

print("Матрица L (множители):\n", L)
print("Матрица U (пивоты на диагонали):\n", U)

# Проверка A = P * L * U
print("Проверка A:\n", P @ L @ U)

# Демонстрация сложности
n = 1000
# Сложность O(n^3) означает, что увеличение n в 10 раз
# увеличит время примерно в 1000 раз.