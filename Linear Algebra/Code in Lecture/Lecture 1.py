import numpy as np

# Определение матрицы A и вектора b из лекции
A = np.array([[2, -1],
              [-1, 2]])
b = np.array([0, 3])

# Решение системы Ax = b (нахождение x)
# Внутри используется метод Гаусса (о котором будет в следующих лекциях)
x = np.linalg.solve(A, b)

print(f"Решение x: {x}")
# Ожидаемый вывод: [1. 2.]

# Проверка через Column Picture (Линейная комбинация)
col1 = A[:, 0]
col2 = A[:, 1]
b_check = x[0] * col1 + x[1] * col2

print(f"Линейная комбинация: {b_check}")
# Ожидаемый вывод: [0. 3.] (совпадает с b)